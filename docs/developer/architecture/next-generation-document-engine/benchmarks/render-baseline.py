#!/usr/bin/env python3
"""Render baseline-2026-11.md from the raw/ TSVs written by measure-images.sh (and build-times.tsv).
Re-run after any measurement: python3 render-baseline.py > baseline-2026-11.md
Numbers are only ever copied from raw/; nothing is typed in by hand."""
import csv, os, re, statistics, sys, datetime
HERE = os.path.dirname(os.path.abspath(__file__)); RAW = os.path.join(HERE, "raw")
def tsv(name):
    p = os.path.join(RAW, name)
    if not os.path.exists(p): return []
    with open(p, newline="") as f: return list(csv.DictReader(f, delimiter="\t"))
def mb(b):
    try: return f"{int(b)/1e6:,.1f} MB"
    except: return str(b)
def med(vals):
    v=[float(x) for x in vals if re.match(r"^\d+(\.\d+)?$", str(x))]
    return (statistics.median(v), len(v)) if v else (None, 0)
out=[]; P=out.append
P("# Baseline measurements — 2026-11-07 (images rebuilt from HEAD, tag `baseline-2026-11`)")
P("")
P("> Generated by `render-baseline.py` from `raw/`. Every number below is copied from a raw file named in its section; "
  "nothing is hand-typed. Measurement host: macOS arm64, Docker 29.9.2 VM with 8 CPUs / 4 GB RAM — a **lower-bound, "
  "non-production** environment (production target per `docs/developer/architecture/load-testing.md` is a 12 vCPU / "
  "48 GB x86 VPS). Treat relative comparisons as meaningful and absolute numbers as indicative only.")
P("")
P("## 1. Build times (`raw/build-times.tsv`, `rebuild-all.sh`, GO_BUILD_PARALLELISM=4)")
P(""); P("| Image | Build seconds | Status | Note |"); P("|---|---:|---|---|")
notes={"fyredocs-base":"Docker layer cache hit — Dockerfile unchanged; apk contents date from the earlier build (versions in §4)",
       "fyredocs-go-builder":"full rebuild: go.mod fingerprint had drifted","convert-from-pdf":"Debian apt: libreoffice-core/writer/calc/impress + poppler + ghostscript + pip",
       "test-binaries":"Alpine apk: libreoffice + tesseract + unoserver","convert-to-pdf":"FROM cached fyredocs-base; Go compile only"}
for r in tsv("build-times.tsv") if tsv("build-times.tsv") else []:
    pass
rows=[l.rstrip("\n").split("\t") for l in open(os.path.join(RAW,"build-times.tsv"))] if os.path.exists(os.path.join(RAW,"build-times.tsv")) else []
for name,sec,st in rows: P(f"| {name} | {sec} | {st} | {notes.get(name,'FROM fyredocs-go-builder; Go compile only')} |")
P("")
P("## 2. Image sizes (`raw/image-sizes.tsv`, `docker image inspect .Size`)")
P(""); P("| Image | Size | Stale local image 3 months earlier (for reference) |"); P("|---|---:|---:|")
stale={"fyredocs-convert-from-pdf":"1.54 GB","fyredocs-convert-to-pdf":"1.17 GB","fyredocs-base":"1.07 GB","fyredocs-optimize-pdf":"325 MB",
       "fyredocs-organize-pdf":"287 MB","fyredocs-ai-service":"56.9 MB","fyredocs-go-builder":"3.82 GB","fyredocs-test-binaries":"2.3 GB",
       "fyredocs-api-gateway":"42.7 MB","fyredocs-job-service":"60.2 MB","fyredocs-document-service":"57.1 MB","fyredocs-user-service":"54.5 MB",
       "fyredocs-notification-service":"56.6 MB","fyredocs-analytics-service":"57.3 MB","fyredocs-auth-service":"56.9 MB"}
for r in sorted(tsv("image-sizes.tsv"), key=lambda r:-int(r["size_bytes"]) if r["size_bytes"].isdigit() else 0):
    P(f"| {r['image']} | {mb(r['size_bytes'])} | {stale.get(r['image'],'—')} |")
P("")
P("Top layers per worker are in `raw/layers-<worker>.txt` (`docker history`). The LibreOffice/apt layer dominates "
  "convert-from-pdf and fyredocs-base; the Go binary is the only non-trivial layer in the scratch-based services.")
P("")
P("## 3. Stripped static binary sizes (`raw/binary-sizes.tsv`; `CGO_ENABLED=0 go build -trimpath -ldflags='-s -w'`)")
P(""); P("| Service | linux/arm64 | linux/amd64 |"); P("|---|---:|---:|")
b={}
for r in tsv("binary-sizes.tsv"): b.setdefault(r["service"],{})[r["goos_goarch"]]=r["size_bytes"]
for svc,d in b.items(): P(f"| {svc} | {mb(d.get('linux_arm64','?'))} | {mb(d.get('linux_amd64','?'))} |")
P("")
P("ai-service is the largest binary (OpenAI client + gopher-lua + websocket + gjson pulled transitively); the four PDF "
  "workers are ~40 MB each because pdfcpu, gorm (with the unused MySQL driver via gorm.io/datatypes), otel/grpc and "
  "quic-go are all linked in. See `../03-heavy-dependency-analysis.md`.")
P("")
P("## 4. Tool versions inside the images (`raw/tool-versions.txt`)")
P(""); P("```")
if os.path.exists(os.path.join(RAW,"tool-versions.txt")): P(open(os.path.join(RAW,"tool-versions.txt")).read().rstrip())
P("```"); P("")
P("Alpine 3.19.9 is end-of-life (2025-11-01). Ghostscript 10.05.1 in optimize-pdf is inside the CVE-2025-59798/59799 "
  "pdfwrite range (fixed in 10.06.0). LibreOffice 7.6.7.2 / 7.4.7.2 are the distro versions, not chosen. unoserver 3.7 "
  "is unpinned (`deployment/base-alpine-libreoffice.Dockerfile:24`).")
P("")
P("## 5. Cold start to readiness (`raw/cold-start.tsv`; container start → `/readyz` 200; 3 runs)")
P(""); P("| Worker | Runs (ms) | Median (ms) | Note |"); P("|---|---|---:|---|")
cs={}
for r in tsv("cold-start.tsv"): cs.setdefault(r["worker"],[]).append((r["cold_start_ms"],r["notes"]))
for w,v in cs.items():
    m,n=med([x for x,_ in v]); P(f"| {w} | {', '.join(x for x,_ in v)} | {int(m) if m is not None else '—'} | {v[0][1]} |")
P("")
P("convert-to-pdf's ~42 s is the entrypoint waiting for a unoserver daemon that can never start (defects D23/D23b in "
  "`../01-existing-system-audit.md` and `../12-performance-architecture.md`), then launching the Go binary anyway; the "
  "pool state is logged as a WARNING only (`raw/startlog-convert-to-pdf.txt`).")
P("")
P("## 6. Idle RSS, 20 s after readiness (`raw/idle-rss.tsv`; `docker stats --no-stream`)")
P(""); P("| Worker | Idle memory | Idle CPU |"); P("|---|---:|---:|")
for r in tsv("idle-rss.tsv"): P(f"| {r['worker']} | {r['idle_rss_bytes']} | {r['idle_cpu_pct']} |")
P("")
P("These are Go-binary-only figures: no LibreOffice daemon was alive in convert-to-pdf (see §5). With a working "
  "2-daemon pool, `deployment/deploy.sh:542` budgets ~300 MB per daemon + ~200 MB Go/buffers; the measured daemon RSS "
  "after a corrected start is in §7.")
P("")
P("## 7. Single-conversion timings and peak RSS (`raw/conversions.tsv`; wall-clock via `docker exec`, peak RSS sampled "
  "from `docker stats` every 250 ms — a lower bound on true peak; 3 runs, median shown)")
P("")
conv={}
for r in tsv("conversions.tsv"): conv.setdefault((r["engine"],r["fixture"],r["size_bytes"]),[]).append(r)
if not conv:
    P("_Not yet measured — step 6 of `measure-images.sh` is pending. Re-run `python3 render-baseline.py > baseline-2026-11.md` afterwards._")
else:
    P("| Engine | Fixture | Input size | Median wall (ms) | Max peak RSS | Runs ok/total |"); P("|---|---|---:|---:|---:|---:|")
    for (e,f,sz),rs in conv.items():
        m,n=med([r["wall_ms"] for r in rs]); pk=max((int(r["peak_rss_bytes"]) for r in rs if str(r["peak_rss_bytes"]).isdigit()), default=0)
        ok=sum(1 for r in rs if r["status"]=="ok")
        P(f"| {e} | {f} | {mb(sz) if sz!='0' else '—'} | {int(m) if m is not None else '—'} | {mb(pk) if pk else '—'} | {ok}/{len(rs)} |")
    P("")
    P("`unoserver-daemon-start-corrected-arg` = time from launching two unoserver daemons **with the corrected arguments** "
      "(`--user-installation /tmp/uno-fixed-NNNN --uno-port NNNN+100`) until the first `unoconvert` succeeds; this is the warm-pool "
      "start-up cost the shipped entrypoint never reaches. `libreoffice-warm-unoconvert` = conversion through that warm daemon; "
      "`libreoffice-cold-headless` = today's actual production path (fresh `libreoffice --headless` per job). Ghostscript args "
      "mirror optimize-pdf's `medium` preset (`optimize-pdf/processing/processing_free.go:106`); OCR mirrors the worker's "
      "pdftoppm→tesseract sequence at 150 DPI, sequential (the worker uses an errgroup of up to 4).")
P("")
P("## 8. Not measured here (and the command that will)")
P("")
P("| Metric | Why not here | Command |")
P("|---|---|---|")
P("| Throughput, concurrent jobs, failure rate, queue wait | 4 GB VM cannot host the full stack; k6 must run off-box | `scripts/k6/run.sh capacity -- -e MODE=jobs …` on the VPS (`scripts/k6/README.md` §5); last run: `scripts/k6/results/capacity-jobs-20260727-234123.md` (9 jobs/min sustained, co-located lower bound) |")
P("| CPU time / utilisation per job | needs cgroup accounting on a quiet host | `docker stats` stream or `cat /sys/fs/cgroup/cpu.stat` inside the worker during a k6 per-group run |")
P("| Average RAM over a run | needs a sustained workload | Prometheus `container_memory_working_set_bytes` during `./run.sh mixed-realistic` |")
P("| Warm LibreOffice numbers under the real worker | pool is dead as shipped (D23/D23b) | after the Q0 fix: `./run.sh convert-to-pdf` ladder; `convert_fallback_total` must be 0 |")
P("| x86 figures | host is arm64 | re-run `measure-images.sh` on the VPS |")
P("")
P(f"_Rendered {datetime.date.today().isoformat()} by `render-baseline.py`._")
print("\n".join(out))
