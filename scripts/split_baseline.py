#!/usr/bin/env python3
"""Split a pg_dump --schema-only dump into per-service goose baseline migrations.

Called by gen-migration-baseline.sh. Every emitted statement is rewritten so
that migration 00001 CONVERGES an existing database onto the dumped schema and
creates that schema on a fresh one — no stamping step, no divergence between
the two paths.

"Converges", not merely "is a no-op": `CREATE TABLE IF NOT EXISTS` alone is
idempotent per TABLE, which silently does nothing about a table that exists but
predates a column the models added later. A subsequent `CREATE INDEX` on that
column then fails with 42703 and takes the service down at boot. So each
`CREATE TABLE` is followed by one `ALTER TABLE ... ADD COLUMN IF NOT EXISTS`
per column.

Caveat worth knowing: a column added to an ALREADY POPULATED table cannot be
`NOT NULL` without a default, so `add_column_stmts` drops `NOT NULL` when there
is no `DEFAULT`. A fresh database still gets the strict definition from the
`CREATE TABLE`; an adopted one gets the column nullable.

Usage: split_baseline.py <dump.sql> <out-dir>
"""
import os
import re
import sys
from typing import Dict, List, Optional

# Table ownership. Each service owns a disjoint set of tables in the shared
# database (see docs/developer/architecture/database.md); the 4 PDF workers own
# none — they read job-service's tables and deliberately do not migrate.
OWNERSHIP = {
    "auth-service": [
        "users", "auth_metadata", "subscription_plans", "user_sessions",
        "password_reset_tokens",
    ],
    "job-service": ["processing_jobs", "file_metadata"],
    "user-service": ["organizations", "memberships"],
    "document-service": [
        "documents", "folders", "tags", "document_tags", "exports",
        "job_workspace_hints",
    ],
    "notification-service": ["notifications"],
    "analytics-service": ["analytics_events", "daily_metrics", "api_metric_samples"],
}

HEADER = """-- Baseline schema for {service}.
--
-- Generated by scripts/gen-migration-baseline.sh from the schema the previous
-- GORM AutoMigrate path produced. Every statement converges the database onto
-- that schema — tables, columns, indexes and constraints are each created only
-- if absent — so this migration creates the schema on a fresh database and
-- brings an existing one (production) up to it without a stamping step.
--
-- The per-column ALTERs matter: CREATE TABLE IF NOT EXISTS is idempotent per
-- TABLE, so on a database whose table predates a column the models added later
-- it would do nothing, and a CREATE INDEX on that column would then fail.
-- Columns added to an existing (possibly populated) table are nullable unless
-- they carry a DEFAULT; a fresh database gets the stricter CREATE TABLE form.
--
-- Do not edit by hand: change the models and regenerate, or add a NEW numbered
-- migration for schema changes from here on.

-- +goose Up
"""

FOOTER_UP = """
-- +goose Down
-- +goose StatementBegin
-- Intentionally empty: the baseline is the starting point of migration history.
-- Rolling it back would drop every table this service owns, which is never a
-- deploy-time operation. Recreate the database instead.
SELECT 1;
-- +goose StatementEnd
"""


def table_of(stmt):
    """Return the table a statement belongs to, or None if it is not ours."""
    patterns = [
        r"CREATE TABLE (?:IF NOT EXISTS )?public\.(\w+)",
        r"ALTER TABLE (?:ONLY )?public\.(\w+)",
        r"CREATE (?:UNIQUE )?INDEX \w+ ON public\.(\w+)",
        r"CREATE SEQUENCE public\.(\w+)_id_seq",
        r"ALTER SEQUENCE public\.(\w+)_id_seq",
    ]
    for p in patterns:
        m = re.search(p, stmt)
        if m:
            return m.group(1)
    return None


# Entries in a CREATE TABLE body that are table-level constraints rather than
# columns. They are re-added separately by the dump's own ALTER TABLE ... ADD
# CONSTRAINT statements, so ADD COLUMN must skip them.
TABLE_CONSTRAINT_RE = re.compile(
    r"^(CONSTRAINT|PRIMARY\s+KEY|UNIQUE|FOREIGN\s+KEY|CHECK|EXCLUDE)\b", re.IGNORECASE
)


def table_body(stmt: str) -> str:
    """The text between the outermost parentheses of a CREATE TABLE."""
    start = stmt.find("(")
    end = stmt.rfind(")")
    if start == -1 or end <= start:
        return ""
    return stmt[start + 1 : end]


def split_top_level(body: str) -> List[str]:
    """Split a CREATE TABLE body on its top-level commas.

    Naive `body.split(",")` would tear apart a CHECK like
    `CHECK ((role = ANY (ARRAY['user'::text, 'admin'::text])))`, so commas are
    only separators at paren depth 0 and outside string literals.
    """
    parts: List[str] = []
    buf: List[str] = []
    depth = 0
    in_string = False
    i = 0
    while i < len(body):
        ch = body[i]
        if in_string:
            buf.append(ch)
            if ch == "'":
                if i + 1 < len(body) and body[i + 1] == "'":  # '' escapes a quote
                    buf.append(body[i + 1])
                    i += 1
                else:
                    in_string = False
        elif ch == "'":
            in_string = True
            buf.append(ch)
        elif ch == "(":
            depth += 1
            buf.append(ch)
        elif ch == ")":
            depth -= 1
            buf.append(ch)
        elif ch == "," and depth == 0:
            parts.append("".join(buf))
            buf = []
        else:
            buf.append(ch)
        i += 1
    parts.append("".join(buf))
    return [p.strip() for p in parts if p.strip()]


def add_column_stmts(table: str, body: str) -> List[str]:
    """One `ADD COLUMN IF NOT EXISTS` per column, to converge an existing table.

    `NOT NULL` is dropped when the column has no `DEFAULT`: adding such a column
    to a table that already has rows is rejected outright, and this statement
    only ever fires on a table that already exists. With a `DEFAULT` present
    Postgres backfills, so `NOT NULL` is kept.
    """
    stmts = []
    for part in split_top_level(body):
        if TABLE_CONSTRAINT_RE.match(part):
            continue
        name, _, definition = part.partition(" ")
        definition = " ".join(definition.split())
        if not name or not definition:
            continue
        if not re.search(r"\bDEFAULT\b", definition, re.IGNORECASE):
            definition = re.sub(
                r"\s*\bNOT\s+NULL\b", "", definition, flags=re.IGNORECASE
            ).strip()
        stmts.append(
            f"ALTER TABLE public.{table} ADD COLUMN IF NOT EXISTS {name} {definition};"
        )
    return stmts


def idempotent(stmt: str) -> str:
    """Rewrite a dump statement so re-running it is harmless."""
    s = stmt.strip()

    if s.startswith("CREATE TABLE public."):
        create = s.replace("CREATE TABLE public.", "CREATE TABLE IF NOT EXISTS public.", 1) + ";"
        # CREATE TABLE IF NOT EXISTS is idempotent per table, not per column —
        # follow it with the ALTERs that bring a pre-existing table up to date.
        table = table_of(s)
        adds = add_column_stmts(table, table_body(s)) if table else []
        return create + "\n\n" + "\n".join(adds) if adds else create

    if s.startswith("CREATE SEQUENCE public."):
        return s.replace("CREATE SEQUENCE public.", "CREATE SEQUENCE IF NOT EXISTS public.", 1) + ";"

    if s.startswith("CREATE INDEX ") or s.startswith("CREATE UNIQUE INDEX "):
        return re.sub(r"^CREATE (UNIQUE )?INDEX ", r"CREATE \1INDEX IF NOT EXISTS ", s, count=1) + ";"

    if s.startswith("ALTER TABLE"):
        # Constraints (PK / UNIQUE / FK / CHECK) have no IF NOT EXISTS form. Skip
        # by name when the constraint is already present, and still guard the
        # ALTER: a pre-existing PK under a DIFFERENT name raises
        # invalid_table_definition (42P16), and a duplicate UNIQUE/FK raises
        # duplicate_object / duplicate_table. The DO block contains semicolons,
        # so it needs explicit goose delimiters (goose otherwise splits on ";").
        m = re.search(r"ADD CONSTRAINT (\w+)", s)
        table = table_of(s)
        indented = "\n".join("        " + line for line in s.split("\n"))
        guard_open, guard_close = "", ""
        if m and table:
            guard_open = (
                f"    IF NOT EXISTS (SELECT 1 FROM pg_constraint\n"
                f"                   WHERE conname = '{m.group(1)}'\n"
                f"                     AND conrelid = 'public.{table}'::regclass) THEN\n"
            )
            guard_close = "    END IF;\n"
        else:
            indented = "\n".join("    " + line for line in s.split("\n"))
        return (
            "-- +goose StatementBegin\n"
            "DO $$ BEGIN\n"
            f"{guard_open}"
            f"{indented};\n"
            f"{guard_close}"
            "EXCEPTION WHEN duplicate_object OR duplicate_table OR invalid_table_definition THEN NULL;\n"
            "END $$;\n"
            "-- +goose StatementEnd"
        )

    return s + ";"


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    dump_path, out_dir = sys.argv[1], sys.argv[2]

    with open(dump_path) as fh:
        raw = fh.read()

    # Strip psql meta-commands and comment/SET preamble, then split on ";\n".
    lines = [
        ln for ln in raw.split("\n")
        if not ln.startswith("--")
        and not ln.startswith("\\")
        and not ln.startswith("SET ")
        and not ln.startswith("SELECT pg_catalog.set_config")
    ]
    body = "\n".join(lines)
    statements = [s.strip() for s in body.split(";\n") if s.strip()]

    owner_of = {t: svc for svc, tables in OWNERSHIP.items() for t in tables}
    per_service = {svc: [] for svc in OWNERSHIP}
    unclaimed = []

    for stmt in statements:
        table = table_of(stmt)
        if table is None:
            if stmt.strip() not in ("", ";"):
                unclaimed.append(stmt.split("\n")[0][:100])
            continue
        svc = owner_of.get(table)
        if svc is None:
            unclaimed.append(f"{table}: {stmt.split(chr(10))[0][:80]}")
            continue
        per_service[svc].append(idempotent(stmt))

    if unclaimed:
        print("WARNING: statements with no owning service:", file=sys.stderr)
        for u in unclaimed:
            print("  " + u, file=sys.stderr)
        return 1

    os.makedirs(out_dir, exist_ok=True)
    for svc, stmts in per_service.items():
        if not stmts:
            print(f"ERROR: no statements captured for {svc}", file=sys.stderr)
            return 1
        content = HEADER.format(service=svc) + "\n\n".join(stmts) + "\n" + FOOTER_UP
        with open(os.path.join(out_dir, f"{svc}.sql"), "w") as fh:
            fh.write(content)
        print(f"  {svc}: {len(stmts)} statements")
    return 0


if __name__ == "__main__":
    sys.exit(main())
