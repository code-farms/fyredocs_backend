#!/usr/bin/env bash
# gen-migration-baseline.sh — (re)generate the version-1 baseline migrations.
#
# The baseline captures the schema the old GORM AutoMigrate path produced, so
# migrations can take over on an EXISTING production database without
# recreating anything. It works by:
#
#   1. starting a throwaway Postgres,
#   2. running each DB-backed service's schema bootstrap against it,
#   3. pg_dump --schema-only, and
#   4. splitting the dump per service by table ownership, rewriting every
#      statement into an idempotent form (IF NOT EXISTS / duplicate_object
#      guards) so migration 00001 is a no-op on a database that already has the
#      schema and creates it on a fresh one.
#
# You normally do NOT need to run this: the baselines are committed. Re-run it
# only to verify the committed baselines still match the models, or to
# regenerate them after a deliberate baseline reset.
#
# Usage:  ./scripts/gen-migration-baseline.sh [--check]
#           --check   generate into a temp dir and diff against the committed
#                     baselines instead of overwriting them.
set -euo pipefail

cd "$(dirname "$0")/.."
ROOT_DIR="$(pwd)"

CHECK_ONLY=0
[ "${1:-}" = "--check" ] && CHECK_ONLY=1

CONTAINER="fyredocs-baseline-pg"
PGPORT="${BASELINE_PG_PORT:-55432}"
WORKDIR="$(mktemp -d)"
trap 'docker rm -f "$CONTAINER" >/dev/null 2>&1 || true; rm -rf "$WORKDIR"' EXIT

echo "==> Starting throwaway Postgres on :$PGPORT"
docker rm -f "$CONTAINER" >/dev/null 2>&1 || true
docker run -d --name "$CONTAINER" \
    -e POSTGRES_PASSWORD=baseline -e POSTGRES_DB=fyredocs \
    -p "${PGPORT}:5432" postgres:18-alpine >/dev/null

for _ in $(seq 1 30); do
    docker exec "$CONTAINER" pg_isready -U postgres >/dev/null 2>&1 && break
    sleep 1
done

export DATABASE_URL="postgresql://postgres:baseline@localhost:${PGPORT}/fyredocs?sslmode=disable"
# Force the legacy AutoMigrate path — that is exactly the schema we are capturing.
export DB_AUTOMIGRATE=true

SERVICES=(auth-service job-service user-service document-service notification-service analytics-service)

echo "==> Bootstrapping schema from each service"
for svc in "${SERVICES[@]}"; do
    mkdir -p "$svc/cmd/genbaseline"
    cat > "$svc/cmd/genbaseline/main.go" <<EOF
// Command genbaseline is generated by scripts/gen-migration-baseline.sh and
// removed again when it finishes. It applies the service's schema bootstrap to
// the scratch database so the baseline migration can be dumped from it.
package main

import "$svc/internal/models"

func main() {
	models.Connect()
	models.Migrate()
}
EOF
    ( cd "$svc" && go run ./cmd/genbaseline >/dev/null 2>&1 ) || {
        echo "ERROR: schema bootstrap failed for $svc" >&2
        rm -rf "$svc/cmd/genbaseline"
        exit 1
    }
    rm -rf "$svc/cmd/genbaseline"
    # Drop the now-empty cmd/ dir if the service has no other commands.
    rmdir "$svc/cmd" 2>/dev/null || true
    echo "    $svc"
done

echo "==> Dumping schema"
docker exec "$CONTAINER" pg_dump -U postgres -d fyredocs \
    --schema-only --no-owner --no-privileges > "$WORKDIR/full-schema.sql"

echo "==> Splitting per service"
OUT_DIR="$WORKDIR/out"
python3 scripts/split_baseline.py "$WORKDIR/full-schema.sql" "$OUT_DIR"

if [ "$CHECK_ONLY" = "1" ]; then
    status=0
    for svc in "${SERVICES[@]}"; do
        committed="$ROOT_DIR/$svc/internal/migrations/00001_baseline.sql"
        generated="$OUT_DIR/$svc.sql"
        if ! diff -u "$committed" "$generated"; then
            echo "DRIFT: $svc baseline differs from the models" >&2
            status=1
        fi
    done
    [ "$status" = "0" ] && echo "==> Baselines match the models"
    exit "$status"
fi

for svc in "${SERVICES[@]}"; do
    mkdir -p "$ROOT_DIR/$svc/internal/migrations"
    cp "$OUT_DIR/$svc.sql" "$ROOT_DIR/$svc/internal/migrations/00001_baseline.sql"
    echo "    wrote $svc/internal/migrations/00001_baseline.sql"
done

echo "==> Done"
