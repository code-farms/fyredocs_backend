// PDF/A-2b via Ghostscript.
//
// PDF/A requires an OutputIntent: an embedded ICC colour profile that pins what
// the document's device colours mean. Ghostscript only adds one when it is given
// a PostScript definition file that loads the profile, which the previous
// invocation never did. Measured 2026-11-08 on the k6 pdf fixture: production's
// Ghostscript 10.00 exited 0 and wrote a file veraPDF rejects (clause 6.2.4.3,
// DeviceGray without a default colour space), and Ghostscript 10.08 aborted on
// the string-typed -sPDFACompatibilityPolicy and left a one-page stub. Ghostscript
// produces level b only (visual preservation); levels a and u need tagging it
// cannot generate.

// pdfaICCEnv overrides sRGB profile discovery, for images that keep the profile
// somewhere unusual.
const pdfaICCEnv = "PDFA_ICC_PROFILE"

// srgbProfileCandidates are where the sRGB profile lives in the images that run
// Ghostscript: Debian bookworm's ghostscript package (convert-from-pdf) and
// Alpine's (the test image). A glob over versioned Ghostscript directories
// catches distributions that keep it under the version number. A var so tests
// can point it elsewhere.
var srgbProfileCandidates = []string{
	"/usr/share/color/icc/ghostscript/srgb.icc",
	"/usr/share/ghostscript/iccprofiles/srgb.icc",
	"/usr/share/ghostscript/*/iccprofiles/srgb.icc",
}

// errNoSRGBProfile means PDF/A cannot be produced on this host. Failing the job
// is deliberate: writing a file without an OutputIntent would hand the user a
// "PDF/A" that any validator rejects.
var errNoSRGBProfile = errors.New("PDF/A conversion unavailable: no sRGB ICC profile found")

// srgbProfilePath returns the sRGB ICC profile Ghostscript should embed:
// PDFA_ICC_PROFILE if set (it must exist), else the first existing candidate.
func srgbProfilePath() (string, error) {
	if p := os.Getenv(pdfaICCEnv); p != "" {
		if _, err := os.Stat(p); err != nil {
			return "", fmt.Errorf("%s=%q: %w", pdfaICCEnv, p, err)
		}
		return p, nil
	}
	for _, pattern := range srgbProfileCandidates {
		matches, _ := filepath.Glob(pattern)
		for _, m := range matches {
			if info, err := os.Stat(m); err == nil && !info.IsDir() {
				return m, nil
			}
		}
	}
	return "", errNoSRGBProfile
}

// psString escapes s for use inside a PostScript (...) string literal.
func psString(s string) string {
	return strings.NewReplacer(`\`, `\\`, `(`, `\(`, `)`, `\)`).Replace(s)
}

// pdfaDefinition returns the PostScript definition file that makes Ghostscript
// embed iccPath as the document's PDF/A OutputIntent. It follows Ghostscript's
// own lib/PDFA_def.ps, with the profile path made absolute: the shipped file
// uses a relative placeholder that differs between distributions.
func pdfaDefinition(iccPath string) string {
	return `%!
% PDF/A definition generated by convert-from-pdf (processing/pdfa.go).
/ICCProfile (` + psString(iccPath) + `) def
[/_objdef {icc_PDFA} /type /stream /OBJ pdfmark
[{icc_PDFA} << /N 3 >> /PUT pdfmark
[{icc_PDFA} ICCProfile (r) file /PUT pdfmark
[/_objdef {OutputIntent_PDFA} /type /dict /OBJ pdfmark
[{OutputIntent_PDFA} <<
  /Type /OutputIntent
  /S /GTS_PDFA1
  /DestOutputProfile {icc_PDFA}
  /OutputConditionIdentifier (sRGB)
>> /PUT pdfmark
[{Catalog} << /OutputIntents [ {OutputIntent_PDFA} ] >> /PUT pdfmark
`
}

// pdfaArgs returns Ghostscript's arguments for a PDF/A-2b conversion of
// inputPath to outputPath using the definition file defPath and profile iccPath.
// -dSAFER confines file access; --permit-file-read lets the definition file open
// the profile. -dPDFACompatibilityPolicy=1 drops features PDF/A forbids (with a
// warning) instead of aborting; it must be the integer -d form.
// -sColorConversionStrategy=RGB matches the RGB output intent.
func pdfaArgs(defPath, iccPath, inputPath, outputPath string) []string {
	return []string{
		"-dPDFA=2",
		"-dBATCH",
		"-dNOPAUSE",
		"-dSAFER",
		"-sDEVICE=pdfwrite",
		"-dPDFACompatibilityPolicy=1",
		"-sColorConversionStrategy=RGB",
		"--permit-file-read=" + iccPath,
		"-sOutputFile=" + outputPath,
		defPath,
		inputPath,
	}
}

// pdfToPdfa converts a PDF to PDF/A-2b via Ghostscript.
//
// Conversion can be lossy where the source uses features PDF/A forbids — notably
// transparency and non-embedded fonts, which get flattened or substituted. That is
// inherent to the format, not a defect here.
func pdfToPdfa(ctx context.Context, inputPath string, outputPath string) error {
	slog.Info("converting PDF to PDF/A", "input", inputPath)

	iccPath, err := srgbProfilePath()
	if err != nil {
		slog.ErrorContext(ctx, "PDF/A conversion unavailable", "error", err, "op", "ghostscript.pdfa")
		return err
	}
	defDir, err := os.MkdirTemp(filepath.Dir(outputPath), "pdfa-def-*")
	if err != nil {
		return fmt.Errorf("create PDF/A definition dir: %w", err)
	}
	defer os.RemoveAll(defDir)
	defPath := filepath.Join(defDir, "PDFA_def.ps")
	if err := os.WriteFile(defPath, []byte(pdfaDefinition(iccPath)), 0o600); err != nil {
		return fmt.Errorf("write PDF/A definition: %w", err)
	}

	cmd := procexec.Command(ctx, "gs", pdfaArgs(defPath, iccPath, inputPath, outputPath)...)
	output, err := cmd.CombinedOutput()
	if err != nil {
		slog.ErrorContext(ctx, "ghostscript PDF/A conversion failed", "error", err, "op", "ghostscript.pdfa", "output", string(output))
		return fmt.Errorf("Ghostscript not available or conversion failed: %w", err)
	}

	slog.Info("PDF/A conversion completed", "output", outputPath, "iccProfile", iccPath)
	return nil
}
